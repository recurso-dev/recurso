// Command gen writes porttest's Unimplemented* types from the interfaces in
// internal/core/port. Run via `go generate ./internal/core/port/porttest`.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

func main() {
	portDir := filepath.Clean(filepath.Join("..")) // porttest/ -> port/
	out := filepath.Join(".", "unimplemented.go")
	if len(os.Args) > 2 {
		portDir, out = os.Args[1], os.Args[2]
	}
	if err := run(portDir, out); err != nil {
		fmt.Fprintln(os.Stderr, "porttest/gen:", err)
		os.Exit(1)
	}
}

type method struct {
	name string
	sig  string // "(params) results" as printed
}

type iface struct {
	name    string
	methods []method
}

func run(portDir, out string) error {
	fset := token.NewFileSet()
	entries, err := os.ReadDir(portDir)
	if err != nil {
		return err
	}
	var files []*ast.File
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(portDir, name), nil, parser.ParseComments)
		if err != nil {
			return err
		}
		if f.Name.Name != "port" {
			return fmt.Errorf("%s: package %s, want port", name, f.Name.Name)
		}
		files = append(files, f)
	}
	imports := map[string]string{}  // local name -> path
	localTypes := map[string]bool{} // exported types declared in package port
	for _, f := range files {
		for _, decl := range f.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				if ts := spec.(*ast.TypeSpec); ts.Name.IsExported() {
					localTypes[ts.Name.Name] = true
				}
			}
		}
	}
	var ifaces []iface
	for _, f := range files {
		for _, imp := range f.Imports {
			p, _ := strconv.Unquote(imp.Path.Value)
			name := filepath.Base(p)
			if imp.Name != nil {
				name = imp.Name.Name
			}
			imports[name] = p
		}
		for _, decl := range f.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts := spec.(*ast.TypeSpec)
				it, ok := ts.Type.(*ast.InterfaceType)
				if !ok || !ts.Name.IsExported() {
					continue
				}
				var ms []method
				for _, fld := range it.Methods.List {
					ft, ok := fld.Type.(*ast.FuncType)
					if !ok {
						return fmt.Errorf("%s embeds %s; embedded interfaces are not supported", ts.Name.Name, exprString(fset, fld.Type))
					}
					for _, n := range fld.Names {
						ms = append(ms, method{name: n.Name, sig: qualify(funcSig(fset, ft), localTypes)})
					}
				}
				ifaces = append(ifaces, iface{name: ts.Name.Name, methods: ms})
			}
		}
	}
	sort.Slice(ifaces, func(i, j int) bool { return ifaces[i].name < ifaces[j].name })

	var body bytes.Buffer
	for _, it := range ifaces {
		fmt.Fprintf(&body, "// Unimplemented%s panics on every %s method; embed it and override the\n// methods the code under test actually calls.\ntype Unimplemented%s struct{}\n\nvar _ port.%s = Unimplemented%s{}\n\n", it.name, it.name, it.name, it.name, it.name)
		for _, m := range it.methods {
			fmt.Fprintf(&body, "func (Unimplemented%s) %s%s {\n\tpanic(\"porttest: %s.%s is not implemented\")\n}\n\n", it.name, m.name, m.sig, it.name, m.name)
		}
	}
	body.WriteString("// allUnimplemented lists every generated type; the package test drives each\n// method through it.\nfunc allUnimplemented() []any {\n\treturn []any{\n")
	for _, it := range ifaces {
		fmt.Fprintf(&body, "\t\tUnimplemented%s{},\n", it.name)
	}
	body.WriteString("\t}\n}\n")
	text := body.String()

	var used []string
	for name, p := range imports {
		if strings.Contains(text, name+".") {
			used = append(used, p)
		}
	}
	used = append(used, "github.com/recurso-dev/recurso/internal/core/port")
	sort.Strings(used)

	var src bytes.Buffer
	src.WriteString("// Code generated by porttest/gen; DO NOT EDIT.\n\npackage porttest\n\nimport (\n")
	for _, p := range used {
		fmt.Fprintf(&src, "\t%q\n", p)
	}
	src.WriteString(")\n\n")
	src.WriteString(text)
	formatted, err := format.Source(src.Bytes())
	if err != nil {
		return fmt.Errorf("format: %w\n%s", err, src.String())
	}
	return os.WriteFile(out, formatted, 0o600) //nolint:gosec // G703: fixed relative paths; go generate runs this inside the porttest directory
}

// qualify prefixes bare references to package-port types with "port.", since
// the generated code lives in porttest.
func qualify(sig string, localTypes map[string]bool) string {
	return identRe.ReplaceAllStringFunc(sig, func(m string) string {
		// m is "<lead><Ident>" where lead is empty or one non-identifier byte.
		lead, name := "", m
		if len(m) > 0 && !isIdentStart(m[0]) {
			lead, name = m[:1], m[1:]
		}
		if localTypes[name] {
			return lead + "port." + name
		}
		return m
	})
}

func isIdentStart(b byte) bool {
	return b == '_' || (b >= 'A' && b <= 'Z') || (b >= 'a' && b <= 'z')
}

// identRe matches identifiers not preceded by a dot (so "domain.Invoice"
// stays untouched while a bare "CardToken" is qualified).
var identRe = regexp.MustCompile(`(?:^|[^.\w])([A-Z]\w*)`)

// funcSig prints "(T1, T2) (R1, R2)" with unnamed parameters, so the
// generated methods never trip unused-parameter checks.
func funcSig(fset *token.FileSet, ft *ast.FuncType) string {
	var params []string
	for _, p := range ft.Params.List {
		t := exprString(fset, p.Type)
		n := len(p.Names)
		if n == 0 {
			n = 1
		}
		for i := 0; i < n; i++ {
			params = append(params, t)
		}
	}
	sig := "(" + strings.Join(params, ", ") + ")"
	if ft.Results == nil || len(ft.Results.List) == 0 {
		return sig
	}
	var results []string
	for _, r := range ft.Results.List {
		t := exprString(fset, r.Type)
		n := len(r.Names)
		if n == 0 {
			n = 1
		}
		for i := 0; i < n; i++ {
			results = append(results, t)
		}
	}
	if len(results) == 1 {
		return sig + " " + results[0]
	}
	return sig + " (" + strings.Join(results, ", ") + ")"
}

func exprString(fset *token.FileSet, e ast.Expr) string {
	var b bytes.Buffer
	_ = printer.Fprint(&b, fset, e)
	return b.String()
}
